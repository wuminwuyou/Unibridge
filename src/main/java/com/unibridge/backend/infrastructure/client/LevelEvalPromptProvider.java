    /**
     * 构建用户消息（将项目招募需求 + 项目内容描述拼接为模型输入）。
     *
     * @param description   项目招募需求（Markdown 原文，明文）
     * @param contentDetail 项目内容详细描述（已解密明文）
     * @return 拼接后的用户消息字符串
     */
